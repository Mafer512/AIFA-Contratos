-- -----------------------------------------------------------------------------
-- 7) Bitácora escrita por la base, no por el navegador
--
-- Hoy el historial lo inserta el cliente (logChange en Dashboard.tsx) con el
-- changed_by que él mismo decide: quien quiera puede firmar un cambio con el
-- id de otra persona. Aquí el autor sale de auth.uid(), que viene del token
-- firmado por Supabase y no se puede falsear desde el navegador. Además queda
-- registrado lo que pase por la API directa, no sólo lo que pase por la app.
--
-- El formato de "changes" es el mismo arreglo {field, before, after} que ya
-- pinta la pestaña Historial.
-- -----------------------------------------------------------------------------
create or replace function public.estatus_2027_audit()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_old     jsonb := case when tg_op = 'INSERT' then null else to_jsonb(old) end;
  v_new     jsonb := case when tg_op = 'DELETE' then null else to_jsonb(new) end;
  v_changes jsonb;
  v_actor   uuid  := auth.uid();
  v_name    text;
  v_role    text;
  v_record  text  := coalesce(v_new ->> 'ID', v_old ->> 'ID');
begin
  select p.full_name, p.role into v_name, v_role
    from public.profiles p where p.id = v_actor;

  if tg_op = 'UPDATE' then
    select jsonb_agg(jsonb_build_object('field', k, 'before', v_old -> k, 'after', v_new -> k))
      into v_changes
      from jsonb_object_keys(v_old || v_new) as k
      -- updated_at cambia en cada guardado; anotarlo sólo ensucia la bitácora.
     where k <> 'updated_at'
       and (v_old -> k) is distinct from (v_new -> k);
    -- Un UPDATE que no cambió nada no merece renglón.
    if v_changes is null then return new; end if;
  else
    select jsonb_agg(jsonb_build_object(
             'field', k,
             'before', case when tg_op = 'DELETE' then v_old -> k else null end,
             'after',  case when tg_op = 'INSERT' then v_new -> k else null end))
      into v_changes
      from jsonb_object_keys(coalesce(v_new, v_old)) as k;
  end if;

  insert into public.change_history (
    table_name, record_id, action, changed_by, changed_by_name, changed_by_role,
    changes, previous_data, new_data
  ) values (
    'estatus_2027', v_record, tg_op, v_actor::text, v_name, v_role,
    v_changes, v_old, v_new
  );

  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

