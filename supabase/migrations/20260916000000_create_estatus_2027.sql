-- -----------------------------------------------------------------------------
-- 5) Seguridad: RLS por rol
--
-- El rol vive en public.profiles. Leerlo desde una política sobre otra tabla
-- exige SECURITY DEFINER: si la política consultara profiles directamente, la
-- RLS de profiles se evaluaría otra vez y Postgres corta por recursión.
-- search_path fijo para que nadie pueda anteponer un esquema propio con una
-- tabla profiles falsa.
-- -----------------------------------------------------------------------------
create or replace function public.current_app_role()
returns text
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select p.role from public.profiles p where p.id = auth.uid()
$$;

revoke all on function public.current_app_role() from public, anon;
grant execute on function public.current_app_role() to authenticated;

alter table public.estatus_2027 enable row level security;

-- La llave anónima viaja dentro del JavaScript que sirve el sitio: cualquiera
-- la puede sacar con abrir las herramientas del navegador. Por eso anon no
-- toca esta tabla ni para leer.
revoke all on public.estatus_2027 from anon, public;
grant select, insert, update, delete on public.estatus_2027 to authenticated;

drop policy if exists estatus_2027_select on public.estatus_2027;
create policy estatus_2027_select
  on public.estatus_2027 for select
  to authenticated
  using (true);

drop policy if exists estatus_2027_insert on public.estatus_2027;
create policy estatus_2027_insert
  on public.estatus_2027 for insert
  to authenticated
  with check (public.current_app_role() in ('ADMIN', 'OPERATOR'));

drop policy if exists estatus_2027_update on public.estatus_2027;
create policy estatus_2027_update
  on public.estatus_2027 for update
  to authenticated
  using (public.current_app_role() in ('ADMIN', 'OPERATOR'))
  with check (public.current_app_role() in ('ADMIN', 'OPERATOR'));

-- Borrar un servicio del programa anual sólo lo hace un administrador.
drop policy if exists estatus_2027_delete on public.estatus_2027;
create policy estatus_2027_delete
  on public.estatus_2027 for delete
  to authenticated
  using (public.current_app_role() = 'ADMIN');

